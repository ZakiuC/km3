#!/usr/bin/env python3
"""Derive addressing/width/access metadata without changing the OD confidence gate."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    source = ROOT / 'device/drivers/pmp4010/driver/od.json'
    entries = json.loads(source.read_text())['entries']
    schema = json.loads((ROOT / 'tools/hwtui/canopen_wire.json').read_text())
    capacity = schema['constants']['SDO_PAYLOAD_CAPACITY']
    text = '// Generated by tools/hwdriver/gen-pmp4010-access.py; DO NOT EDIT.\n'
    text += '// od.json sha256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    text += '#pragma once\n#include "od_generated.hpp"\nnamespace km3::pmp4010::od {\n'
    text += 'struct Access { const char* key; std::size_t entry; std::uint16_t width; bool writable; bool variable_length; };\ninline constexpr Access kAccess[] = {\n'
    widths = {'uint8': 1, 'int8': 1, 'uint16': 2, 'int16': 2, 'uint32': 4, 'int32': 4}
    for i, e in enumerate(entries):
        if e['status'] == 'verified' and e['index'] is not None and e['sub'] is not None and (e['type'] in widths or e['type'] == 'string'):
            text += f'    {{"{e["key"]}", {i}u, {widths.get(e["type"], capacity)}u, {str(e["access"] == "rw").lower()}, {str(e["type"] == "string").lower()}}},\n'
    text += '};\n}  // namespace km3::pmp4010::od\n'
    target = ROOT / 'device/drivers/pmp4010/driver/od_access_generated.hpp'
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('od_access_generated.hpp: stale')
    else:
        target.write_text(text)

if __name__ == '__main__':
    main()
