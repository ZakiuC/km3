#!/usr/bin/env python3
"""Derive addressing/width/access metadata without changing the OD confidence gate."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    source = ROOT / 'device/drivers/pmp4010/driver/od.json'
    entries = json.loads(source.read_text())['entries']
    schema = json.loads((ROOT / 'tools/hwtui/canopen_wire.json').read_text())
    capacity = schema['constants']['SDO_PAYLOAD_CAPACITY']
    text = '// Generated by tools/hwdriver/gen-pmp4010-access.py; DO NOT EDIT.\n'
    text += '// od.json sha256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    text += '#pragma once\n#include "od_generated.hpp"\nnamespace km3::pmp4010::od {\n'
    # entry is the verified parent provenance, while index/sub are the actual
    # wire address (a motion_object may differ from its structural parent).
    text += 'struct Access { const char* key; std::size_t entry; std::uint16_t index; std::uint8_t sub; std::uint16_t width; bool writable; bool variable_length; };\ninline constexpr Access kAccess[] = {\n'
    widths = {'uint8': 1, 'int8': 1, 'uint16': 2, 'int16': 2, 'uint32': 4, 'int32': 4}
    seen_keys, seen_addresses = set(), set()
    for i, e in enumerate(entries):
        if e['status'] != 'verified':
            continue
        for item in [e, *e.get('motion_objects', [])]:
            if item['index'] is None or item['sub'] is None or (item['type'] not in widths and item['type'] != 'string'):
                continue
            address = (int(item['index'], 0), item['sub'])
            if item['key'] in seen_keys or address in seen_addresses:
                raise SystemExit(f'duplicate access metadata: {item["key"]}')
            seen_keys.add(item['key'])
            seen_addresses.add(address)
            # Newly exposed structural children are read-only driver policy.
            # Their hardware rw permission does not authorize live calibration
            # or limit changes through the generic write API.
            # E06 10.3 表10-7: device 60B1h is RW, but this driver only
            # reads it as a CSV guard. Offset writes are not implemented.
            # 605Dh is likewise RW hardware metadata, exposed only for Halt
            # probe reads; generic numeric/raw writes must remain closed.
            writable = (item is e and item.get('access', e['access']) == 'rw'
                        and item['key'] not in ('velocity_offset', 'halt_option'))
            text += f'    {{"{item["key"]}", {i}u, 0x{address[0]:04X}u, {address[1]}u, {widths.get(item["type"], capacity)}u, {str(writable).lower()}, {str(item["type"] == "string").lower()}}},\n'
    text += '};\n}  // namespace km3::pmp4010::od\n'
    target = ROOT / 'device/drivers/pmp4010/driver/od_access_generated.hpp'
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('od_access_generated.hpp: stale')
    else:
        target.write_text(text)

if __name__ == '__main__':
    main()
