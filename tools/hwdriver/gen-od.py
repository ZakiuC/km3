# -*- coding: utf-8 -*-
"""从 od.json 生成两份产物：C++ 常量头与 Python 常量模块。

    python3 tools/hwdriver/gen-od.py --model PMP4010            # 生成（覆盖）
    python3 tools/hwdriver/gen-od.py --model PMP4010 --check    # 只比对，不一致退出 1

产物：
    device/drivers/<型号>/driver/od_generated.hpp    C++ 侧常量
    tools/hwtui/canopen_consts.py                    板端工具侧常量（OD_VERIFIED = False）

为什么必须生成，而不是手写两份：

    同一个对象字典索引要同时被设备端 C++ 驱动与板端工具
    （tools/hwtui/canopen.py 那一层）使用。手写两份的必然结果是
    改了一处漏一处，而漏改的现场表现是「工具读的索引与驱动写的不一样」——
    报一个看着合理的错值，或者按错的距离移动。因此：

        od.json 是常量的唯一来源，两份产物都不得手改，
        第三条路径必须读产物。

    产物首行有字面量标记 GENERATED BY ... DO NOT EDIT。
    tools/check-manual-citations.sh 用它识别生成物并跳过（生成物里的索引
    不是手写的，不该要求它逐行带引用——引用在 od.json 的 cite 字段里）；
    --check 则让「手改产物」在 CI 里直接失败。

--check 的存在理由：没有它，手改生成物能一路过 CI，
直到下次有人重跑生成器时被静默覆盖——那是最坏的一类缺陷，
因为它留下了一段「源码与 od.json 不一致」的窗口，而这段窗口里
代码看起来是对的。

退出码：0 成功/一致；1 不一致（--check）；2 参数或输入错误。

与 docs/架构设计/硬件驱动开发路径.md 第 4、5 步的对应关系：
  第 4 步定义 od.json 的字段语义（status 三值、cite 规则）；
  第 5 步只认本脚本的 --model 与 --check。两者的引用解析规则必须一致，
  因此校验逻辑只写在本文件里，第 11 步的检查器 import 它，不另写一份。
"""

import argparse
import difflib
import io
import json
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# 产物首行的字面量标记。**两个产物用同一个字符串**：
# check-manual-citations.sh 与人工排查都靠它的存在判断「这文件是生成物」。
GEN_MARKER = "GENERATED BY tools/hwdriver/gen-od.py — DO NOT EDIT"

# od.json 的 status 三值。定义见硬件驱动开发路径.md 第 4 步。
# 只有 verified 能产出可用常量：assumed 是另一类状态，不是 verified 的弱化版，
# 它让「有人口头说过」与「手册写了」在代码里可区分。把 assumed 当 verified 用
# 等于删掉这条区分。
STATUS_VERIFIED = "verified"
STATUS_ASSUMED = "assumed"
STATUS_UNVERIFIED = "unverified"
VALID_STATUS = (STATUS_UNVERIFIED, STATUS_ASSUMED, STATUS_VERIFIED)

# od.json 的 type -> (C++ 类型, 最小值, 最大值)。
# bitfield / enum / table / scaling / bool / string 不是整数常量，不进 C++ 常量表，
# 它们描述的是**结构**而非取值，硬塞成一个 uint 只会掩盖「这条还没填」。
CPP_INT_TYPES = {
    "uint8": ("std::uint8_t", 0, 0xFF),
    "int8": ("std::int8_t", -0x80, 0x7F),
    "uint16": ("std::uint16_t", 0, 0xFFFF),
    "int16": ("std::int16_t", -0x8000, 0x7FFF),
    "uint32": ("std::uint32_t", 0, 0xFFFFFFFF),
    "int32": ("std::int32_t", -0x80000000, 0x7FFFFFFF),
}


def model_to_code(model):
    """型号 -> 驱动代号（小写命名空间）。与 new-driver.sh 用**同一**规则。

    两处必须一致：本脚本用它组 C++ 命名空间（km3::<代号>）与文件名词干，
    而 new-driver.sh 用它命名目录与 CMake 目标。规则漂移的后果是生成物
    写进一个与驱动目录名不匹配的命名空间，链接期才报错。
    """
    code = "".join(ch if ch.isalnum() else "_" for ch in model).lower()
    while "__" in code:
        code = code.replace("__", "_")
    return code.strip("_")


def normalize_entries(doc):
    """统一条目标识字段：两种写法并存，这里归一成 key。

      PMP4010 的 od.json 用 "key"（controlword）
      模板的 od.json 用 "name"（control_word）

    必须归一，否则生成器要按入口分叉，而分叉的代价是
    「两条路径只有一条被真正跑过」，另一条的错误要等到现场才暴露。

    归一放在**读入处**而不是渲染处：下游代码只看 key，
    不必知道磁盘上用的是哪个字段名。

    name 与 key 的职责不同，两者都保留：
      key  —— 稳定标识，派生 C++/Python 常量名，必须 ASCII
      name —— 人类可读名（可以是中文），只出现在注释与工具输出里
    """
    for e in doc.get("entries", []):
        if not isinstance(e, dict):
            continue
        if "key" not in e and "name" in e:
            e["key"] = e["name"]
        if "name" not in e and "key" in e:
            e["name"] = e["key"]
    return doc


def load_od(path):
    try:
        with io.open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
    except FileNotFoundError:
        sys.stderr.write("错误：找不到 %s\n" % path)
        sys.exit(2)
    except ValueError as exc:
        sys.stderr.write("错误：%s 不是合法 JSON：%s\n" % (path, exc))
        sys.exit(2)
    if not isinstance(doc, dict):
        sys.stderr.write("错误：%s 的顶层必须是 JSON 对象\n" % path)
        sys.exit(2)
    return normalize_entries(doc)


def _parse_int(raw):
    """把 index 的写法解析成整数。无法解析时返回 None（**不是**报错）。

    od.json 里 index 写 "_model_" 之外的地方可能是 "0x6040" 字符串、整数，
    或 null（手册未到）。null 是**正常状态**，见 validate() 的处理。
    用 int(x, 0) 而不是 int(x)：后者不认 0x 前缀，会把 "0x6040" 当非法——
    而 0x 恰好是本仓库唯一使用的写法。
    """
    if raw is None:
        return None
    if isinstance(raw, bool):
        return None
    if isinstance(raw, int):
        return raw
    if isinstance(raw, str):
        text = raw.strip()
        if not text:
            return None
        try:
            return int(text, 0)
        except ValueError:
            return None
    return None


def validate(doc, model):
    """生成前的完整性校验。返回 (是否通过, 未核对条目列表)。

    **校验失败时不出任何产物**：产物是「事实」的载体，
    半对不对的产物比没有产物更危险——它会被 include / import，然后被当成事实用。

    校验项与硬件驱动开发路径.md 第 4 步的 jq 命令一一对应，
    这里用 Python 重写是因为 jq 不是本仓库的依赖（板端与 CI 都不保证有）。
    """
    ok = True
    entries = doc.get("entries")
    if not isinstance(entries, list) or not entries:
        sys.stderr.write("错误：od.json 缺少非空的 entries 数组。\n")
        return False, []

    # device 段与 entries 段**都要**有 status/cite 成对出现（第 4 步的 jq 检查
    # 用 `.. | objects | select(has("status"))` 递归全文件，这里跟着做）。
    dev = doc.get("device", {})
    for key, block in sorted(dev.items()):
        if not isinstance(block, dict) or "status" not in block:
            continue
        if "cite" not in block:
            sys.stderr.write("错误：device.%s 有 status 但没有 cite 字段。\n" % key)
            ok = False
            continue
        if not _check_status_cite(block, "device.%s" % key):
            ok = False

    seen_keys, seen_idx = set(), {}
    for i, e in enumerate(entries):
        where = "entries[%d]" % i
        key = e.get("key") or e.get("name")
        if not key:
            sys.stderr.write("错误：%s 缺 key/name。\n" % where)
            ok = False
            continue
        where = "%s(%s)" % (where, key)
        if key in seen_keys:
            # 重复 key 会让生成物里出现两个同名常量，编译期报 redefinition，
            # 而错误信息指向生成物而不是 od.json。
            sys.stderr.write("错误：条目 key 重复：%s\n" % key)
            ok = False
        seen_keys.add(key)

        if "status" not in e:
            sys.stderr.write("错误：%s 缺 status 字段（三值：%s）。\n"
                             % (where, " / ".join(VALID_STATUS)))
            ok = False
        if "cite" not in e:
            sys.stderr.write("错误：%s 缺 cite 字段（未核对应为 null，不能省略）。\n" % where)
            ok = False
        if "status" in e and "cite" in e and not _check_status_cite(e, where):
            ok = False

        idx = _parse_int(e.get("index"))
        sub = _parse_int(e.get("sub"))
        if idx is not None:
            key_idx = (idx, sub if sub is not None else 0)
            if key_idx in seen_idx:
                # 同一 (索引, 子索引) 出现两次：有人抄写时把两条并成了一条，
                # 或复制粘贴后忘了改 index。两者都会让标度用错。
                sys.stderr.write("错误：索引 0x%04X:%s 在 %s 与 %s 上重复。\n"
                                 % (idx, key_idx[1], seen_idx[key_idx], where))
                ok = False
            seen_idx[key_idx] = where

        # index 的合法范围是**对象字典索引的 16 位**，
        # 与条目自己的 type 无关。
        #
        # 实测踩过：一度拿 type 的范围去卡 index（uint8 的条目要求 index <= 0xFF），
        # 于是每一个索引 > 0xFF 的 uint8 条目都被误判 —— 0x1001（error register）
        # 是最典型的一个。type 描述的是**该索引处存的值**有多宽，
        # 不是索引本身有多宽。两者混用会把合法的字典表判成错的。
        if idx is not None and not (0 <= idx <= 0xFFFF):
            sys.stderr.write(
                "错误：%s 的 index 0x%X 超出对象字典索引的 16 位范围。\n"
                "      这通常是抄错一位（如 0x6040 抄成 0x60400）。\n" % (where, idx))
            ok = False
        # type 本身必须是受控表里的值：它决定 C++ 侧的类型与 Python 侧的常量。
        # 未知 type 不报错在这里，而在渲染期报——渲染期能给出可用取值清单。

        # index 写了但解析不出数字 —— 这比留 null 更坏。
        #
        # 实测踩过：把 index 写成 "0x60400" 之外的笔误（例如 "60h"、带了全角字符）
        # 会让 _parse_int 返回 None，而 None 与「手册未到、索引留空」走的是
        # **同一条**渲染路径，于是产物里静默出现一个 kIndexUnset。
        # 一个手滑的笔误就这样伪装成了「尚未核对」——而两者的处置完全不同：
        # 前者要改 od.json，后者要等手册。故此处显式拒绝。
        raw_index = e.get("index")
        if raw_index is not None and idx is None:
            sys.stderr.write(
                "错误：%s 的 index %r 无法解析成整数。\n"
                "      索引要么写 '0x6040' 这样的十六进制串，要么写 null（手册未到）。\n"
                "      写成无法解析的值会静默退化成「未核对」，掩盖真正的笔误。\n"
                % (where, raw_index))
            ok = False

    unverified = [e for e in entries if e.get("status") != STATUS_VERIFIED]
    return ok, unverified


def _check_status_cite(block, where):
    """status 与 cite 的组合规则。返回是否通过。

    这两条是本仓库**溯源闸门**的核心不变量，必须在生成期就守住：

      verified 无 cite   —— 把猜测洗成了事实，而现场表现是按错的距离移动
      unverified 带 cite —— 自相矛盾，读的人不知道信哪一边
                            说明有人把来源抄进了没核对的条目里
    """
    status = block.get("status")
    cite = block.get("cite")
    ok = True
    if status not in VALID_STATUS:
        sys.stderr.write("错误：%s 的 status '%s' 非法（只能取 %s）。\n"
                         % (where, status, " / ".join(VALID_STATUS)))
        return False
    if status == STATUS_VERIFIED and not (isinstance(cite, str) and cite.strip()):
        sys.stderr.write("错误：%s 标为 verified 但没有非空 cite。\n"
                         "      verified 必须给出手册出处，否则等于把猜测洗成事实。\n" % where)
        ok = False
    if status in (STATUS_UNVERIFIED, STATUS_ASSUMED) and cite is not None:
        sys.stderr.write("错误：%s 标为 %s 却带了 cite（%s）。\n"
                         "      两者矛盾：%s 的 cite 必须是 null。\n"
                         % (where, status, cite, status))
        ok = False
    return ok


def cpp_const_name(key):
    """条目 key -> C++ 常量名 kFooBar。"""
    return "k" + "".join(p[:1].upper() + p[1:] for p in key.replace("-", "_").split("_") if p)


def cpp_string_literal(text):
    """C++ 字符串字面量转义。

    cite 里可能有反斜杠或引号（Windows 风格路径、手册标题里的引号）；
    不转义会生成一个编不过的头文件，而错误信息指向生成物而非 od.json。
    """
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def manual_dir_name(root, model, declared):
    """手册目录在磁盘上的**真实**名字。

    依次尝试：目录名、od.json 的 device.model、以及大小写不敏感的唯一匹配。
    都找不到时退回 device.model（若也没有则退回目录名）——手册还没到位是
    正常状态，此时生成物里的路径只是"将来该放哪"，不构成错误。
    """
    base = os.path.join(root, "docs", "硬件手册")
    candidates = [declared, model]
    if os.path.isdir(base):
        on_disk = [n for n in os.listdir(base)
                   if os.path.isdir(os.path.join(base, n))]
        lowered = {n.lower(): n for n in on_disk}
        for cand in candidates:
            if cand and cand.lower() in lowered:
                return lowered[cand.lower()]
    for cand in candidates:
        if cand:
            return cand
    return model


def render_hpp(doc, model, code, od_sha, manual_dir):
    dev = doc.get("device", {})
    entries = doc["entries"]
    unverified = [e for e in entries if e.get("status") != STATUS_VERIFIED]
    all_verified = not unverified
    macro = "%s_OD_VERIFIED" % code.upper()
    ns = "km3::%s" % code

    o = []
    w = o.append
    w("// %s" % GEN_MARKER)
    w("//")
    w("// 型号：%s（驱动代号 %s，命名空间 %s）" % (model, code, ns))
    w("// 来源：device/drivers/%s/driver/od.json" % model)
    w("// 来源 sha256：%s" % od_sha)
    w("//")
    w("// 手改本文件会在 `python3 tools/hwdriver/gen-od.py --model %s --check`" % model)
    w("// 下失败，进而让 CI 变红。要改常量请改 od.json 再重新生成。")
    w("// 解释这一规则的原因：同一个索引要被 C++ 驱动与板端工具同时使用，")
    w("// 手改一处会让两边读的字典分家，而分家的表现是「工具说可以动、驱动编不过」")
    w("// 或更糟——两边都以为自己对。")
    w("//")
    w("// 关于首行标记与 #error 的关系（本文件唯一的设计要点）：")
    w("//")
    w("//   只有 status=verified 的条目才产出可用常量。其余条目 index 为 null，")
    w("//   而一个 null 索引生成的代码，唯一正确的行为是**编不过**，")
    w("//   而不是生成一份看起来能编译、跑起来把报文发到错误 COB-ID 上的驱动。")
    w("//")
    w("//   **驱动侧的 kOdVerified 定义在驱动自己的头文件里，不在这里。**")
    w("//   两个头文件曾各定义一次同名常量，单测同时 include 两者时直接")
    w("//   \"redefinition\" 编不过。事实只有一份，定义也只有一处；")
    w("//   手册到达、od.json 填实之后，驱动改为 include 本文件并删掉那份定义。")
    w("//")
    w("// 旁路的唯一用途：CI 在无手册时保证骨架可构建、以及未接电机的控制器回环验证。")
    w("// 见 device/drivers/_template/CMakeLists.txt 的 KM3_ALLOW_UNVERIFIED_OD")
    w("// 与 docs/架构设计/硬件驱动开发路径.md 的硬停规则第 2 条。")
    w("")
    w("#pragma once")
    w("")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w("// 未定义时取 0 —— 于是「忘了定义」与「显式定义为 0」行为一致，都是崩溃式失败。")
    w("// 若直接写 #if !%s 而宏未定义，-Wundef 下会报未定义标识符，" % macro)
    w("// 把「未核对」这条**业务事实**混进「宏忘了定义」这类构建噪声里。")
    w("#ifndef %s" % macro)
    w("#define %s %d" % (macro, 1 if all_verified else 0))
    w("#endif")
    w("")
    w("#if !%s" % macro)
    # 判定必须是**真值**而不是「宏是否存在」。
    #
    # `#ifndef KM3_ALLOW_UNVERIFIED_OD` 的漏洞：`-DKM3_ALLOW_UNVERIFIED_OD=0`
    # 也算「已定义」，于是 #error 被跳过 —— 一个本想**关闭**旁路、显式写下
    # `=0` 的构建脚本，反而静默打开了它。这类"写反了却看不出来"的配置
    # 正是这道闸门要防的，不能让它自己被同样的手法绕过。
    #
    # 用 `!defined(X) || !X` 而不是 `#if !X`：后者在宏未定义时触发 -Wundef
    # 警告，把「未核对」这条业务事实混进「宏忘了定义」这类构建噪声里。
    w("#if !defined(KM3_ALLOW_UNVERIFIED_OD) || !KM3_ALLOW_UNVERIFIED_OD")
    w('#error "%s 对象字典未验证（driver/od.json 里仍有 %d 条 status != verified）。'
      ' 本文件在手册到达并填实之前不得使用：索引未知就发帧等于拿真实电机盲试。'
      ' 仅在校验工具与 CI 中可定义 KM3_ALLOW_UNVERIFIED_OD=1（或 %s=1）关闭本守卫。'
      ' 阻塞项见 docs/硬件手册/%s/README.md。"'
      % (model, len(unverified), macro, manual_dir))
    w("#else")
    w("// 显式旁路。保留一个可被 grep 到的标记，使「哪些产物是在未核对状态下构建的」")
    w("// 在事后可查：一个能在未核对状态下构建的二进制，不应该出现在接了电机的现场。")
    w('#pragma message("KM3: 正在以未核对的对象字典构建 %s 驱动（KM3_ALLOW_UNVERIFIED_OD=1）")'
      % model)
    w("#endif")
    w("#endif")
    w("")
    w("namespace %s::od {" % ns)
    w("")
    w("// 与 od.json 的 status 字段一一对应，缺一不可。")
    w("enum class OdStatus : std::uint8_t {")
    w("    Unverified = 0,  // 无任何依据")
    w("    Assumed = 1,     // 有口头依据，仍需书面确认")
    w("    Verified = 2,    // 有 cite 指向具体文件与页码")
    w("};")
    w("")
    w("// 条目的置信度。生成物里逐条给出，供驱动与工具用**同一判据**决定")
    w("// 「这条能不能用」——判据只写在这里，不在调用点各判一次。")
    w("struct OdEntry {")
    w("    const char* key;        // od.json 的 key，稳定标识（中文名会漂移）")
    w("    std::uint16_t index;    // 对象字典索引；未核对时为 0xFFFF（哨兵，不是合法索引）")
    w("    std::uint8_t sub;       // 子索引；未核对时为 0")
    w("    OdStatus status;")
    w("    const char* cite;       // 手册出处；未核对时为空字符串")
    w("    bool verified;          // status == Verified，即「可以拿去发帧」")
    w("};")
    w("")
    w("// 未核对索引的哨兵值。用它而不是 0：0 是**合法**的对象字典索引，")
    w("// 拿 0 当「未填」会让一条漏填的条目看起来像一条指向 0x0000 的真实条目。")
    w("inline constexpr std::uint16_t kIndexUnset = 0xFFFF;")
    w("")
    w("inline constexpr std::uint32_t kEntryCount = %d;" % len(entries))
    w("")
    w("inline constexpr OdEntry kEntries[kEntryCount] = {")
    for e in entries:
        key = e["key"]
        idx = _parse_int(e.get("index"))
        sub = _parse_int(e.get("sub"))
        status = e.get("status", STATUS_UNVERIFIED)
        cite = e.get("cite")
        status_enum = {"unverified": "OdStatus::Unverified",
                       "assumed": "OdStatus::Assumed",
                       "verified": "OdStatus::Verified"}.get(status, "OdStatus::Unverified")
        usable = (status == STATUS_VERIFIED and isinstance(cite, str) and cite.strip())
        idx_text = ("0x%04Xu" % idx) if idx is not None and 0 <= idx <= 0xFFFF else "kIndexUnset"
        sub_text = "%du" % sub if sub is not None and 0 <= sub <= 255 else "0u"
        cite_text = cpp_string_literal(cite) if isinstance(cite, str) and cite else '""'
        comment = e.get("name") or key
        w("    // %s" % comment)
        if not usable:
            w("    //   溯源: 未核对（见 docs/硬件手册/%s/README.md 的未确认项清单）" % manual_dir)
        w("    {%s, %s, %s, %s, %s, %s}," % (
            cpp_string_literal(key), idx_text, sub_text, status_enum, cite_text,
            "true" if usable else "false"))
    w("};")
    w("")
    w("// 未核对条目数。工具打印的「N 项对象字典未核对」用这个 N，")
    w("// 与 od.json 同一个来源，不各自再算一遍。")
    w("inline constexpr std::uint32_t kUnverifiedCount = %d;" % len(unverified))
    w("")
    w("// 当前对象字典的整体置信度。全部 verified 才为 true。")
    w("inline constexpr bool kOdVerified = (%s != 0);" % macro)
    w("")
    w("// 取一条已核对条目的索引。未核对时返回哨兵 —— 调用方必须自己判 usable，")
    w("// 因此本函数**不**替它兜底。")
    w("constexpr std::uint16_t %s_index(std::size_t entry) noexcept {" % code)
    w("    if (entry >= kEntryCount || !kEntries[entry].verified) {")
    w("        return kIndexUnset;")
    w("    }")
    w("    return kEntries[entry].index;")
    w("}")
    w("")
    w("}  // namespace %s::od" % ns)
    w("")
    return "\n".join(o)


def render_py(doc, model, code, od_sha, manual_dir):
    dev = doc.get("device", {})
    entries = doc["entries"]
    unverified = [e for e in entries if e.get("status") != STATUS_VERIFIED]
    all_verified = not unverified

    o = []
    w = o.append
    w("# -*- coding: utf-8 -*-")
    w("# %s" % GEN_MARKER)
    w("#")
    w("# 型号：%s（驱动代号 %s）" % (model, code))
    w("# 来源：device/drivers/%s/driver/od.json" % model)
    w("# 来源 sha256：%s" % od_sha)
    w("#")
    w("# 板端工具（tools/hwtui/）用的常量。**不要在这里手改**：")
    w("# 手改会在 `python3 tools/hwdriver/gen-od.py --model %s --check` 下失败，" % model)
    w("# 并且下次重新生成时被静默覆盖——于是有一段时间板上的工具与")
    w("# C++ 驱动读的不是同一份字典。")
    w("#")
    w("# 为什么板端不直接读 od.json：")
    w("#   od.json 是**带溯源注释的输入文件**，格式会随手册落地而增删字段。")
    w("#   板端每次点命令都解析一遍 JSON 会把工具与输入格式绑死；")
    w("#   生成成扁平常量后，工具侧只依赖这个稳定接口。")
    w("")
    w('"""硬件对象字典常量（生成物，勿手改）。"""')
    w("")
    w("MODEL = %r" % dev.get("model", model))
    w("DRIVER_CODE = %r" % code)
    w("LOGICAL_BUS = %r" % (dev.get("logical_bus") or ""))
    w("PROTOCOL = %r" % (dev.get("protocol") or ""))
    w("UNITS_ON_BUS = %r" % (dev.get("units_on_bus") or 0))
    w("")
    w("# 全部条目是否已由厂家手册核对。False 时工具必须显式提示「未核对」，")
    w("# 不得显示一个看着合理的默认值——未核对却显示成已核对，比不显示更糟。")
    w("# 判据与 C++ 侧同一来源（都由 od.json 的 status 算出），不各自再算一遍。")
    w("OD_VERIFIED = %s" % ("True" if all_verified else "False"))
    w("")
    w("# 未核对条目数。工具打印的「N 项对象字典未核对」用这个 N，")
    w("# 措辞与 device/drivers/<型号>/tools/<型号>.py 的 refuse_motion() 一致，")
    w("# 运维脚本会 grep 那一行。")
    w("OD_UNVERIFIED_COUNT = %d" % len(unverified))
    w("OD_ENTRY_COUNT = %d" % len(entries))
    w("")
    w("# 未核对索引的哨兵。用它而不是 0：0 是**合法**的对象字典索引，")
    w("# 拿 0 当「未填」会让一条漏填的条目看起来像一条指向 0x0000 的真实条目。")
    w("# 与 C++ 侧 kIndexUnset 同一个值。")
    w("INDEX_UNSET = 0xFFFF")
    w("")
    w("# 条目 key -> 索引。未核对的条目值为 INDEX_UNSET —— **不是 0，也不是省略**：")
    w("# 省略键会让 OD_INDEX.get(key) 与「未核对」不可区分，于是调用方无法")
    w("# 区分「这个索引不能用」与「这个 key 不存在」，而那两件事的处置完全不同。")
    for e in entries:
        idx = _parse_int(e.get("index"))
        usable = (e.get("status") == STATUS_VERIFIED
                  and isinstance(e.get("cite"), str) and e["cite"].strip())
        val = "0x%04X" % idx if (usable and idx is not None and 0 <= idx <= 0xFFFF) else "INDEX_UNSET"
        w("%s = %s" % (e["key"].upper(), val))
    w("")
    w("# 索引 -> 条目描述。板端工具用它把原始索引翻译成人能读的名字，")
    w("# 并标注「这条是未核对的」——未核对却显示成已核对，比不显示更糟。")
    w("# 字段：(key, 中文名, 子索引, 类型, 是否可用, cite)")
    w("OD_BY_INDEX = {")
    for e in entries:
        idx = _parse_int(e.get("index"))
        sub = _parse_int(e.get("sub"))
        usable = (e.get("status") == STATUS_VERIFIED
                  and isinstance(e.get("cite"), str) and e["cite"].strip())
        if not (usable and idx is not None and 0 <= idx <= 0xFFFF):
            continue   # 未核对的不进反查表：它没有可用来反查的索引
        w("    0x%04X: (%r, %r, %d, %r, %r, %r),"
          % (idx, e["key"], e.get("name", e["key"]), sub if sub is not None else 0,
             e.get("type") or "", True, e.get("cite")))
    w("}")
    w("")
    w("# key -> (索引, 子索引, 中文名, 可用?)。" )
    w("# 未核对的条目同样进表，但 usable 为 False —— 工具据此拒绝运动类操作，")
    w("# 而不是抛 KeyError（那会让「未核对」表现为一个看不出原因的崩溃）。")
    w("OD_BY_KEY = {")
    for e in entries:
        idx = _parse_int(e.get("index"))
        sub = _parse_int(e.get("sub"))
        usable = (e.get("status") == STATUS_VERIFIED
                  and isinstance(e.get("cite"), str) and e["cite"].strip())
        val = "0x%04X" % idx if (usable and idx is not None and 0 <= idx <= 0xFFFF) else "INDEX_UNSET"
        w("    %r: (%s, %d, %r, %r),"
          % (e["key"], val, sub if sub is not None else 0,
             e.get("name", e["key"]), usable))
    w("}")
    w("")
    w("")
    w("def describe(index, sub=0):")
    w('    """把索引翻成可读描述；未核对时显式带「未核对」字样。')
    w("")
    w('    工具显示一个索引时**必须**走这里：直接打印数字会让人以为它是')
    w("    已确认的厂家事实，而它可能只是 CiA 402 的惯例值。")
    w('    """')
    w("    if index == INDEX_UNSET:")
    w('        return "未核对"')
    w("    info = OD_BY_INDEX.get(index)")
    w("    if info is None:")
    w("        # 总线扫描会看到我们不认识的索引，那是正常现象，不该让工具崩。")
    w('        return "0x%04X:%d（不在本驱动的对象字典内）" % (index, sub)')
    w("    key, name, ent_sub, typ, usable, cite = info")
    w('    return "0x%04X:%d %s %s  [%s] %s" % (index, ent_sub, key, name, typ, cite)')
    w("")
    return "\n".join(o)


def sha256_of_file(path):
    import hashlib
    h = hashlib.sha256()
    with io.open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def check_one(path, content):
    """--check：比对磁盘产物与按 od.json 生成的内容。True 表示不一致。

    不一致时打印 unified diff —— 只说「不一致」会让人去手工对两份文件，
    而这类缺陷几乎总是「有人手改了一行」。
    """
    try:
        with io.open(path, encoding="utf-8") as fh:
            current = fh.read()
    except FileNotFoundError:
        # 产物缺失也算不一致：CI 里生成物是必交的，
        # 缺失说明有人删了它而没改 od.json（或从没跑过生成器）。
        sys.stderr.write("  !! 生成物缺失：%s\n" % path)
        return True
    if current == content:
        print("  一致   %s" % path)
        return False
    sys.stderr.write("  !! 生成物与 od.json 不一致：%s\n" % path)
    diff = difflib.unified_diff(
        current.splitlines(), content.splitlines(),
        fromfile=path + "（磁盘上）", tofile=path + "（按 od.json 生成）", lineterm="")
    for line in list(diff)[:60]:
        sys.stderr.write("     %s\n" % line)
    return True


def write_one(path, content):
    d = os.path.dirname(path)
    if d and not os.path.isdir(d):
        os.makedirs(d)
    # newline="\n" 显式指定 LF：生成物进 git，CRLF 会让 --check 每次都报
    # 不一致，而差分看起来一模一样（只差不可见的行尾）。
    with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    print("  已写入 %s" % path)


def main(argv):
    ap = argparse.ArgumentParser(
        description="从 od.json 生成 od_generated.hpp 与 canopen_consts.py")
    ap.add_argument("--model", required=True,
                    help="型号，例如 PMP4010（决定读哪个 od.json、写哪两个产物）")
    ap.add_argument("--check", action="store_true",
                    help="不写文件，只比对产物与 od.json；不一致退出 1（进 CI，禁止手改生成物）")
    ap.add_argument("--allow-placeholder", action="store_true",
                    help="允许 od.json 的 model 是占位（仅供 device/drivers/_template 使用）")
    ap.add_argument("--repo-root", default=REPO_ROOT,
                    help="仓库根，默认按本脚本位置推断（测试用）")
    args = ap.parse_args(argv)

    root = os.path.abspath(args.repo_root)
    model = args.model
    code = model_to_code(model)

    od_path = os.path.join(root, "device", "drivers", model, "driver", "od.json")
    if not os.path.isfile(od_path):
        sys.stderr.write(
            "错误：找不到 %s\n"
            "      型号目录要先由 tools/hwdriver/new-driver.sh 生成：\n"
            "        bash tools/hwdriver/new-driver.sh %s --apply\n" % (od_path, model))
        return 2

    doc = load_od(od_path)

    # 型号一致性：od.json 的 device.model 必须与目录名相同。
    #
    # 为什么必须查：复制一个型号目录改成新型号时，最容易漏改的就是文件内容。
    # 漏了的后果不是报错，而是**生成物里的溯源路径指向另一个型号的手册目录**，
    # 看起来完全正常，直到有人照着它去翻一份不存在的手册。
    #
    # _template 例外：模板自己的 od.json 写着占位型号，
    # 而它必须能被生成（否则模板没人验证过，模板里的错误只能在第一次真用时暴露）。
    # 比较用小写：目录名约定是小写型号（PMP4010 -> pmp4010，见
    # device/drivers/_template/README.md 的占位约定），而 od.json 的
    # device.model 写厂家铭牌上的大写写法。两者是同一个型号的两种拼法，
    # 因此只比较大小写折叠后的形式 —— **不比较拼写**，拼写不同仍然是错误
    # （那是复制目录后漏改型号的信号）。
    declared = (doc.get("device") or {}).get("model")
    if declared and declared.lower() != model.lower() and not args.allow_placeholder:
        sys.stderr.write(
            "错误：%s 里的 device.model 是 '%s'，但目录名是 '%s'。\n"
            "      两者必须指向同一个型号（大小写可不同，拼写不可），\n"
            "      否则生成物里的溯源路径会指向错的型号。\n"
            "      （模板目录用 --allow-placeholder）\n"
            % (os.path.relpath(od_path, root), declared, model))
        return 2

    ok, unverified = validate(doc, model)
    if not ok:
        sys.stderr.write("\n结果：od.json 未通过校验，**不生成任何产物**。\n"
                         "      依据见 docs/架构设计/硬件驱动开发路径.md 第 4 步。\n")
        return 2

    od_sha = sha256_of_file(od_path)
    # 手册目录名按**磁盘上的实际写法**解析，而不是拿目录名去拼。
    #
    # 驱动目录约定小写（pmp4010），手册目录用厂家铭牌写法（PMP4010）——
    # 两者是同一个型号的两种拼法，硬要用一个会逼人二选一，而无论选哪个
    # 都会与另一处既有约定冲突（见 check-manual-citations.sh 的同名注释）。
    #
    # 拿目录名去拼的后果：生成物里写出 `docs/硬件手册/pmp4010/README.md`，
    # 在区分大小写的 Linux 上指不到任何文件。这不是报错，是一条**指错路**的
    # 注释——读的人照着它去找一份不存在的手册，而生成物看起来完全正常。
    manual_dir = manual_dir_name(root, model, declared)

    targets = [
        (os.path.join(root, "device", "drivers", model, "driver", "od_generated.hpp"),
         render_hpp(doc, model, code, od_sha, manual_dir)),
        (os.path.join(root, "tools", "hwtui", "canopen_consts.py"),
         render_py(doc, model, code, od_sha, manual_dir)),
    ]

    if args.check:
        print("==> 校验 %s 的两份生成物（--check）" % model)
    else:
        print("==> 生成 %s 的常量（来源 %s）"
              % (model, os.path.relpath(od_path, root)))

    changed = False
    for path, content in targets:
        if args.check:
            if check_one(path, content):
                changed = True
        else:
            write_one(path, content)

    if args.check:
        if changed:
            sys.stderr.write(
                "\n结果：不一致。生成物不得手改——\n"
                "      改 device/drivers/%s/driver/od.json 后重跑：\n"
                "        python3 tools/hwdriver/gen-od.py --model %s\n" % (model, model))
            return 1
        print("结果：两份生成物都与 od.json 一致")
        return 0

    print()
    print("==> 条目 %d 条，其中未核对 %d 条 -> %s_OD_VERIFIED = %d"
          % (len(doc["entries"]), len(unverified), code.upper(),
             0 if unverified else 1))
    if unverified:
        print("    手册未落地时这是预期状态：运动路径会被 #error 拦住（编译期），")
        print("    只有 CI 与未接电机的回环验证才该定义 KM3_ALLOW_UNVERIFIED_OD=1。")
        print("    消解办法：把资料放进 docs/硬件手册/%s/，在 od.json 里把 status 改成" % manual_dir)
        print("    verified 并把 cite 写成「<仓库相对路径>:<章节或页码>」，再重新生成。")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
