#!/usr/bin/env python3
"""Generate shared wire/state constants, not language-specific transaction executors."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads((ROOT / 'tools/hwtui/canopen_wire.json').read_text())
    entries = schema['constants']
    citations = schema.get('citations', {})
    py = '# Generated by tools/hwdriver/gen-canopen.py; DO NOT EDIT.\n'
    cpp = '// Generated by tools/hwdriver/gen-canopen.py; DO NOT EDIT.\n#pragma once\n#include <cstdint>\nnamespace km3::canopen::wire {\n'
    for key, value in entries.items():
        if not isinstance(value, int) or value < 0 or value > 0xffffffff:
            raise ValueError(key)
        if key in citations:
            py += '# ' + citations[key] + '\n'
            cpp += '// ' + citations[key] + '\n'
        py += f'{key} = 0x{value:X}\n'
        cpp += f'inline constexpr std::uint32_t {key} = 0x{value:X}u;\n'
    cpp += '}  // namespace km3::canopen::wire\n'
    # The exact same complete dialogues are replayed by Python and C++ tests.
    vectors = json.loads((ROOT / 'tools/hwtui/vectors/canopen_golden.json').read_text())['vectors']
    gold = '// Generated by tools/hwdriver/gen-canopen.py; DO NOT EDIT.\n#pragma once\n'
    gold += 'namespace golden {\nstruct Frame { unsigned id; unsigned char data[8]; };\n'
    gold += 'struct Pair { Frame request; Frame response; };\n'
    gold += 'struct Case { const char* name; unsigned node, index, sub; bool write; unsigned abort; const Pair* pairs; unsigned count; const unsigned char* payload; unsigned size; bool protocol_error = false; };\n'
    cases = []
    for v in vectors:
        if v['kind'] not in ('sdo_expedited_read', 'sdo_expedited_write', 'sdo_segmented_read', 'sdo_segmented_write', 'sdo_abort', 'sdo_protocol_error') or 'expected_frames_note' in v:
            continue
        pairs = v['expected_frames']
        name = v['name']
        gold += f'inline constexpr Pair {name}_pairs[] = {{\n'
        for pair in pairs:
            parts = []
            for direction in ('request', 'response'):
                frame = pair[direction]
                data = bytes.fromhex(frame['data'])
                if len(data) != 8:
                    raise ValueError(f'{name}: non-classic SDO vector')
                parts.append('{' + str(int(frame['id'], 16)) + ', {' + ','.join(str(b) for b in data) + '}}')
            gold += '    {' + ','.join(parts) + '},\n'
        gold += '};\n'
        sequence = v.get('object_value_hex_sequence_zero_to')
        payload = bytes(range(sequence)) if sequence is not None else bytes.fromhex(v.get('write_value', v.get('expected_value', '')))
        gold += f'inline constexpr unsigned char {name}_payload[] = {{' + (','.join(str(b) for b in payload) or '0') + '};\n'
        abort = v.get('expect_abort_code', 0)
        if isinstance(abort, str):
            abort = int(abort, 16)
        write = pairs[0]['request']['data'].split()[0] != '40'
        cases.append(f'    {{"{name}", {v["node_id"]}, {v["index"]}, {v["subindex"]}, {str(write).lower()}, {abort}u, {name}_pairs, {len(pairs)}, {name}_payload, {len(payload)}, {str(v.get("expect_protocol_error", False)).lower()}}},')
    gold += 'inline constexpr Case cases[] = {\n' + '\n'.join(cases) + '\n};\n}\n'
    for name, content in [('tools/hwtui/canopen_wire.py', py), ('device/include/km3/canopen_wire_generated.hpp', cpp), ('device/drivers/pmp4010/tests/canopen_vectors_generated.hpp', gold)]:
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{name}: stale generated protocol definitions')
        else:
            path.write_text(content)

if __name__ == '__main__':
    main()
